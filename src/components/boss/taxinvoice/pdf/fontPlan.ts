function inHangulFont(cp: number): boolean {
  for (let i = 0; i < HANGUL_FONT_RANGES.length; i += 2) {
    if (cp < HANGUL_FONT_RANGES[i]) return false;
    if (cp <= HANGUL_FONT_RANGES[i + 1]) return true;
  }
  return false;
}

// 기본 글꼴에 확실히 있는 기호만 — 모르면 큰 글꼴로 넘긴다(빈칸보다 내려받기가 낫다)
const BASE_SAFE_SYMBOLS = new Set(Array.from('·※×÷₩￦㎡―–—‐‘’“”…〈〉《》「」『』【】○●□■△▲▽▼◇◆☆★→←↑↓（）［］｛｝，．：；！？％＆＠＃＊＋－／＝～ㆍ一金整'));

let ksHangul: Set<string> | null | undefined;

/** KS X 1001 한글 2,350자 — 브라우저 EUC-KR 해독기로 만든다. 해독기가 없으면 null(한글은 모두 큰 글꼴로) */
function ksHangulSet(): Set<string> | null {
  if (ksHangul !== undefined) return ksHangul;
  try {
    const dec = new TextDecoder('euc-kr');
    const set = new Set<string>();
    for (let b1 = 0xb0; b1 <= 0xc8; b1++) {
      for (let b2 = 0xa1; b2 <= 0xfe; b2++) {
        const ch = dec.decode(new Uint8Array([b1, b2]));
        if (ch.length === 1 && ch >= '가' && ch <= '힣') set.add(ch);
      }
    }
    ksHangul = set.size === 2350 ? set : null;
  } catch {
    ksHangul = null;
  }
  return ksHangul;
}

function inBaseFont(ch: string): boolean {
  const cp = ch.codePointAt(0) ?? 0;
  if (cp >= 0x20 && cp <= 0x7e) return true;
  if (ch >= '가' && ch <= '힣') return ksHangulSet()?.has(ch) ?? false;
  return BASE_SAFE_SYMBOLS.has(ch);
}

export interface FontPlan {
  family: string;
  /** 큰 글꼴(한글 전체)이 필요한가 */
  needsHangulFont: boolean;
  /** 어느 글꼴에도 없어 PDF 에서 빠지는 글자 — 화면이 알려 준다 */
  unsupported: string[];
}

/** 문서에 찍을 글자들을 보고 글꼴을 고른다 */
export function planPdfFont(texts: (string | null | undefined)[]): FontPlan {
  let needsHangulFont = false;
  const unsupported = new Set<string>();
  for (const t of texts) {
    if (!t) continue;
    for (const ch of Array.from(t)) {
      if (ch === '\n' || ch === '\r' || ch === '\t') continue;
      if (inBaseFont(ch)) continue;
      needsHangulFont = true;
      const cp = ch.codePointAt(0) ?? 0;
      if (!inHangulFont(cp)) unsupported.add(ch);
    }
  }
  return {
    family: needsHangulFont ? HANGUL_FONT_FAMILY : BASE_FONT_FAMILY,
    needsHangulFont,
    unsupported: Array.from(unsupported),
  };
}
